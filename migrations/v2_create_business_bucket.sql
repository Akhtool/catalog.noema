-- Миграция: Создание bucket 'business' для хранения логотипов и обложек
-- Дата: 2026-01-27
-- Описание: Создание публичного bucket для загрузки изображений бизнесов

-- ============================================================================
-- 1. Создание bucket 'business'
-- ============================================================================

-- Проверяем, существует ли bucket
DO $$
BEGIN
  -- Создаём bucket, если его нет
  IF NOT EXISTS (
    SELECT 1 FROM storage.buckets WHERE name = 'business'
  ) THEN
    INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    VALUES (
      'business',
      'business',
      true, -- Публичный bucket
      5242880, -- 5MB лимит на файл
      ARRAY['image/jpeg', 'image/png', 'image/webp', 'image/gif'] -- Только изображения
    );
  END IF;
END $$;

-- ============================================================================
-- 2. Проверка создания
-- ============================================================================

-- Проверяем, что bucket создан
SELECT 
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
FROM storage.buckets 
WHERE name = 'business';

-- ============================================================================
-- Примечания
-- ============================================================================

-- 1. Bucket создан как публичный (public = true)
-- 2. Лимит размера файла: 5MB
-- 3. Разрешены только изображения: JPEG, PNG, WebP, GIF
-- 4. После создания bucket выполните миграцию v2_storage_policies.sql
--    для настройки RLS политик (если нужны дополнительные ограничения)
